import 'package:cloud_firestore/cloud_firestore.dart';

import '../../domain/entities/lost_found_item.dart';
import '../../domain/enums/item_status.dart';

class LostFoundItemModel {
  final String id;
  final String name;
  final String description;
  final String location;
  final String status;
  final DateTime createdAt;

  const LostFoundItemModel({
    required this.id,
    required this.name,
    required this.description,
    required this.location,
    required this.status,
    required this.createdAt,
  });

  factory LostFoundItemModel.fromMap(
    Map<String, dynamic> map,
    String documentId,
  ) {
    final name = map['name'];
    final description = map['description'];
    final location = map['location'];
    final status = map['status'];
    if (name is! String ||
        description is! String ||
        location is! String ||
        status is! String) {
      throw const FormatException('Invalid lost-found document fields.');
    }
    if (status != 'lost' && status != 'found') {
      throw FormatException('Unknown item status: $status.');
    }

    // created_at is written with FieldValue.serverTimestamp() (DATABASE.md).
    // Legacy documents and pending writes may not have a timestamp yet.
    // Keep their creation time unknown instead of assigning the read time.
    final createdAtValue = map['created_at'];
    final DateTime createdAt;
    if (createdAtValue is Timestamp) {
      createdAt = createdAtValue.toDate().toUtc();
    } else if (createdAtValue == null) {
      createdAt = LostFoundItem.unknownCreatedAt;
    } else {
      throw const FormatException('Invalid document creation timestamp.');
    }

    return LostFoundItemModel(
      id: documentId,
      name: name,
      description: description,
      location: location,
      status: status,
      createdAt: createdAt,
    );
  }

  factory LostFoundItemModel.fromFirestore(
    DocumentSnapshot<Map<String, dynamic>> doc,
  ) {
    return LostFoundItemModel.fromMap(doc.data() ?? {}, doc.id);
  }

  factory LostFoundItemModel.fromEntity(LostFoundItem item) {
    final String status;
    switch (item.status) {
      case ItemStatus.lost:
        status = 'lost';
      case ItemStatus.found:
        status = 'found';
    }

    return LostFoundItemModel(
      id: item.id,
      name: item.name,
      description: item.description,
      location: item.location,
      status: status,
      createdAt: item.createdAt,
    );
  }

  /// Payload for the create operation.
  ///
  /// The document id is generated by Firestore and therefore not included.
  /// `created_at` always uses the server timestamp (DATABASE.md): any
  /// [createdAt] carried by the entity is ignored on write, the server wins.
  Map<String, dynamic> toMap() {
    return {
      'name': name,
      'description': description,
      'location': location,
      'status': status,
      'created_at': FieldValue.serverTimestamp(),
    };
  }

  LostFoundItem toEntity() {
    final ItemStatus itemStatus;
    switch (status) {
      case 'lost':
        itemStatus = ItemStatus.lost;
      case 'found':
        itemStatus = ItemStatus.found;
      default:
        throw FormatException('Unknown item status: $status.');
    }

    return LostFoundItem(
      id: id,
      name: name,
      description: description,
      location: location,
      status: itemStatus,
      createdAt: createdAt,
    );
  }
}
